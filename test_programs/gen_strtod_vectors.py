#!/usr/bin/env python3
"""Generate the test vectors for strtod_test.c, as strtod_vectors.h:
numbers with their correctly rounded double, float and, for m68k's 80-bit
extended long double, long double.

    python3 gen_strtod_vectors.py strtod_vectors.h

The expectations come from exact rational arithmetic, rounding half to
even.  The long double is given as its 12 bytes, only for normal numbers.
The same seed gives the same vectors every time."""
import random, struct, sys
from fractions import Fraction

random.seed(20261027)

def round_to_binary(q, mant_bits, emin, emax):
    """q > 0 rational -> (m, e) with value m * 2^e, m < 2^mant_bits, round
    half to even; e >= emin - (mant_bits - 1) (denormals).  Returns None on
    overflow (beyond emax)."""
    # find e such that 2^(mant_bits-1) <= q / 2^e < 2^mant_bits
    e = q.numerator.bit_length() - q.denominator.bit_length() - (mant_bits - 1)
    while q / Fraction(2) ** e >= 2 ** mant_bits:
        e += 1
    while q / Fraction(2) ** e < 2 ** (mant_bits - 1):
        e -= 1
    min_e = emin - (mant_bits - 1)
    if e < min_e:
        e = min_e
    s = q / Fraction(2) ** e
    m = s.numerator // s.denominator
    r = s - m
    if r > Fraction(1, 2) or (r == Fraction(1, 2) and m % 2 == 1):
        m += 1
    if m == 2 ** mant_bits:
        m //= 2
        e += 1
    if m != 0 and e + (mant_bits - 1) > emax:
        return None
    return m, e

def to_double_bits(q, neg):
    if q == 0:
        return (1 << 63) if neg else 0
    r = round_to_binary(q, 53, -1022, 1023)
    if r is None:
        bits = 0x7FF << 52
    else:
        m, e = r
        if m == 0:
            bits = 0
        elif m < 2 ** 52:                       # denormal
            bits = m
        else:
            bits = ((e + 52 + 1023) << 52) | (m - 2 ** 52)
    return bits | ((1 << 63) if neg else 0)

def to_float_bits(q, neg):
    if q == 0:
        return (1 << 31) if neg else 0
    r = round_to_binary(q, 24, -126, 127)
    if r is None:
        bits = 0xFF << 23
    else:
        m, e = r
        if m == 0:
            bits = 0
        elif m < 2 ** 23:
            bits = m
        else:
            bits = ((e + 23 + 127) << 23) | (m - 2 ** 23)
    return bits | ((1 << 31) if neg else 0)

def to_m68k_ldbl_bytes(q, neg):
    """m68k extended: sign+15-bit exponent (bias 16383), 16 zero bits,
    64-bit mantissa with explicit integer bit.  Normal numbers only."""
    if q == 0:
        return None
    r = round_to_binary(q, 64, -16382, 16383)
    if r is None:
        return None
    m, e = r
    if m < 2 ** 63:
        return None                              # denormal: skip
    exp = e + 63 + 16383
    if not (1 <= exp <= 0x7FFE):
        return None
    hi = exp | (0x8000 if neg else 0)
    return struct.pack('>HHQ', hi, 0, m)

def decimal_string():
    ndig = random.choice([1, 2, 3, 5, 8, 12, 15, 16, 17, 18, 19, 20, 22, 25])
    digits = str(random.randint(1, 9)) + ''.join(random.choice('0123456789') for _ in range(ndig - 1))
    kind = random.random()
    if kind < 0.35:
        exp = random.randint(-30, 30)
    elif kind < 0.7:
        exp = random.randint(-320, 310)
    else:
        exp = random.randint(-45, 40)            # float range
    point = random.randint(0, len(digits))
    s = digits[:point] + ('.' if point < len(digits) else '') + digits[point:]
    if s.startswith('.'):
        s = '0' + s
    s += 'e%d' % (exp - (len(digits) - point))
    if random.random() < 0.2:
        s = '-' + s
    return s

def value_of(s):
    neg = s.startswith('-')
    t = s.lstrip('+-')
    if t[:2].lower() == '0x':
        mant, _, p = t[2:].lower().partition('p')
        ip, _, fp = mant.partition('.')
        v = Fraction(int((ip + fp) or '0', 16), 16 ** len(fp)) * Fraction(2) ** int(p or 0)
        return v, neg
    mant, _, ex = t.lower().partition('e')
    ip, _, fp = mant.partition('.')
    v = Fraction(int(ip + fp), 10 ** len(fp)) * Fraction(10) ** int(ex or 0)
    return v, neg

cases = [decimal_string() for _ in range(1900)]
cases += [
    "1.7976931348623157e308", "1.7976931348623158e308", "1.797693134862315807e308",
    "2.2250738585072014e-308", "2.2250738585072011e-308", "4.9406564584124654e-324",
    "2.4703282292062328e-324", "1e-310", "3.4028234663852886e38", "1.17549435e-38",
    "1.4e-45", "0.1", "0.2", "0.3", "1e23", "8.98846567431158e307", "9007199254740993",
    "9007199254740992.5", "123456789012345678901234567890", "1.5e300", "12e30",
    "0x1p4", "0x1.8p1", "0xA.8p-2", "0x1.fffffffffffffp1023", "0x1p-1074", "0x.0000000000001p-1022",
]
for _ in range(73):
    m = random.getrandbits(random.choice([8, 24, 53, 60]))
    cases.append('0x%xp%d' % (m, random.randint(-1080, 1000)))

out = ['/* Generated by gen_strtod_vectors.py; do not edit. */', '#include <stdint.h>',
       'struct vec { const char *s; uint64_t d; uint32_t f; int has_ld; unsigned char ld[12]; };',
       'static const struct vec vecs[] = {']
for s in cases:
    v, neg = value_of(s)
    d = to_double_bits(v, neg)
    f = to_float_bits(v, neg)
    ld = to_m68k_ldbl_bytes(v, neg)
    ldtxt = '{' + ','.join('0x%02x' % b for b in (ld or bytes(12))) + '}'
    out.append('  { "%s", 0x%016xULL, 0x%08xU, %d, %s },' % (s, d, f, 1 if ld else 0, ldtxt))
out.append('};')
out.append('#define NUM_VECS (sizeof(vecs) / sizeof(vecs[0]))')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(len(cases), 'vectors')
